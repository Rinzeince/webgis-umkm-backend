print("\n📌 [MODIFY 3.1] Imputasi Missing Values dengan Median...")
print("   Justifikasi: Median lebih robust terhadap outlier dibanding Mean.")
print("   Dengan n=16, satu nilai ekstrem dapat sangat menggeser Mean.\n")
df_processed = df_raw.copy()
# ── FLAG PENTING: Kecamatan dengan banyak NA ────────────────────────────────
# Kecamatan yang memiliki banyak kolom UMKM bernilai NA akan mendapat nilai
# imputasi median untuk SEMUA fitur UMKM-nya. Ini dapat menyebabkan
# 'imputation bias': kecamatan tersebut terlihat memiliki profil UMKM rata-rata
# padahal sebenarnya tidak ada data yang valid.
# Catatan ini penting untuk narasi keterbatasan penelitian di Bab IV skripsi.
