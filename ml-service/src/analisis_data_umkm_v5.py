if len(kec_banyak_na) > 0:
    print("  ⚠️  PERINGATAN — Kecamatan dengan ≥3 kolom UMKM bernilai NA:")
    print(kec_banyak_na.to_string(index=False))
    print("  Interpretasi cluster kecamatan ini PERLU DIVALIDASI secara kualitatif")
    print("  karena nilainya sebagian besar berasal dari imputasi, bukan data riil.")
    # Simpan daftar untuk digunakan pada ASSESS
    KEG_IMPUTASI_TINGGI = kec_banyak_na['nama_kecamatan'].tolist()
else:
    KEG_IMPUTASI_TINGGI = []
    print("  ✅ Tidak ada kecamatan dengan banyak NA pada kolom UMKM.")
df_processed = df_raw.drop(columns=['n_umkm_na'], errors='ignore').copy()
